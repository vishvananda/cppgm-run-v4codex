unsigned packed_builtin(TextView name)
{
    if (name.size < 16 || name.data[0] != '_') return 0;
    for (unsigned i = 1; i < sizeof(entries)/sizeof(*entries); ++i)
        if (name.equals(entries[i].name)) return i;
    return 0;
}
const PackedBuiltin& packed_builtin(unsigned id) { return entries[id]; }
